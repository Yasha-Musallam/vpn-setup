#!/usr/bin/env bash
# проверка, что значение по умолчанию для I1 раскрывается ЦЕЛИКОМ (без кавычек)
unset AWG_I1
I1=${AWG_I1:-'<r 2><b 0x858000010001000000000669636c6f756403636f6d0000010001c00c000100010000105a00044d583737>'}
printf 'default=[%s]\n' "$I1"
[[ "$I1" == "<r 2><b 0x858000010001000000000669636c6f756403636f6d0000010001c00c000100010000105a00044d583737>" ]] \
  && echo "I1 по умолчанию: OK" || { echo "I1 по умолчанию: FAIL"; exit 1; }

AWG_I1='<c>'
I1=${AWG_I1:-'<r 2>'}
printf 'override=[%s]\n' "$I1"
[[ "$I1" == "<c>" ]] && echo "I1 из переменной окружения: OK" || { echo "I1 override: FAIL"; exit 1; }
